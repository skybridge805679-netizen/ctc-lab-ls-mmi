"""Build sourced exercise limits, keeping total-exam, scenario and railway timings separate."""
import json,hashlib
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
data=json.loads((ROOT/'references/transcriptions/assessment-timing.json').read_text())
for record in [data,*data['emergency'].values(),*data['scenarios'].values()]:
 assert hashlib.sha256((ROOT/record['source']).read_bytes()).hexdigest()==record['sha256']
for item in [*data['emergency'].values(),*data['scenarios'].values()]:assert item['minutes'] and all(0<m<=60 for m in item['minutes'])
(ROOT/'simulator/engine/assessment-data.js').write_text("(function(root){'use strict';\n// Generated by tools/build-assessment-timing.py from references/transcriptions/assessment-timing.json.\nconst data="+json.dumps(data,ensure_ascii=False,separators=(',',':'))+";\nif(typeof module!=='undefined')module.exports=data;else root.SimAssessmentData=data;\n})(typeof globalThis!=='undefined'?globalThis:this);\n")
print('Compiled total 60 minutes, 9 emergency limits and 1 refuge limit; no invented per-subject allocation')
