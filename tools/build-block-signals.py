"""Compile reviewed PPT block numbers. Never infer a number from circuit order."""
from pathlib import Path
import json,hashlib
ROOT=Path(__file__).resolve().parents[1]
source=json.loads((ROOT/'references/transcriptions/block-signals.json').read_text())
assert hashlib.sha256((ROOT/source['source']).read_bytes()).hexdigest()==source['sha256']
data={};seen=set()
for item in source['indicators']:
 assert item['reviewed'] and item['id'] not in seen
 assert isinstance(item['number'],int) and 1<=item['number']<=99
 assert item['side'] in ['above','below'] and item['stem'] in ['left','right'] and -.5<=item['fraction']<=1.5
 seen.add(item['id']);data.setdefault(item['station'],[]).append({k:item[k] for k in ['id','number','code','anchorCode','side','fraction','stem']})
(ROOT/'simulator/engine/block-signals.js').write_text("(function(root){'use strict';\n// Generated by tools/build-block-signals.py from reviewed PPT source; display identifiers only.\nconst data="+json.dumps(data,ensure_ascii=False,separators=(',',':'))+";\nif(typeof module!=='undefined')module.exports=data;else root.SimBlockSignals=data;\n})(typeof globalThis!=='undefined'?globalThis:this);\n")
print('Compiled',len(seen),'block numbers across',len(data),'stations')
