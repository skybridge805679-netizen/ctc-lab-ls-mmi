// Builds simulator/route-menus.js (LS route-menu whitelist) from the verified hand-transcribed lists.
// Usage: node tools/build-route-menus.cjs [file ...]   (default: references/route-menus/ls-route-menus-transcribed.txt)
// Every listed route must exist in the simulator's derived routes, otherwise the build fails.
const fs=require('fs'),path=require('path'),Core=require('../simulator/core.js');
const files=process.argv.slice(2).length?process.argv.slice(2):[path.join(__dirname,'../references/route-menus/ls-route-menus-transcribed.txt')];
const menus={};
for(const file of files){let st=null;
 for(const l of fs.readFileSync(file,'utf8').split('\n').filter(Boolean)){
  if(!/ - /.test(l)){st=l.trim();menus[st]=menus[st]||{};continue;}
  for(const g of l.split(/\s+(?=\d+[A-Z]?\s-\s)/)){const [sig,rest]=g.split(' - ');
   for(const r of rest.split(',').map(s=>s.trim())){const m=r.match(/^RT_(\w+?)_(\w+)$/);
    if(!m||m[1]!==sig.trim())throw new Error(`bad token ${st} ${sig} ${r}`);
    (menus[st][m[1]]=menus[st][m[1]]||[]).push(m[2]);}}}}
for(const [st,sigs] of Object.entries(menus)){const C=Core.forStation(st);
 for(const [sig,dests] of Object.entries(sigs))for(const d of dests)if(!C.routes[sig+'-'+d])throw new Error(`route ${st} ${sig}-${d} is not derivable from the wiring`);}
const js="(function(root){\n'use strict';\n// Generated by tools/build-route-menus.cjs from references/route-menus. Routes the real LS offers per signal (verified stations only).\nconst data="+JSON.stringify(menus)+";\nif(typeof module!=='undefined')module.exports=data;else root.SimRouteMenus=data;\n})(typeof window!=='undefined'?window:globalThis);\n";
fs.writeFileSync(path.join(__dirname,'../simulator/route-menus.js'),js);
console.log('route-menus.js:',Object.entries(menus).map(([s,v])=>s+' '+Object.values(v).flat().length).join(', '));
