"""Combine two independent source inventories into reviewed SVG scene data.
Reads Claude's station-local cells and GPT's page-wide section inventory. No raster is shipped to the renderer.
"""
import json,re,subprocess
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
from PIL import Image
import numpy as np
from scipy.ndimage import label,find_objects
info=json.loads(subprocess.check_output(['node','-e',"const N=require('./simulator/network'),W=require('./simulator/wings'),D=require('./simulator/wiring').data;console.log(JSON.stringify(N.stations.filter(s=>s.controlled).map(s=>({id:s.id,page:s.map.page,ref:s.map.referenceWindow,bounds:s.map.view.bounds,size:D[s.id].size,cells:W[s.id].cells}))))"],cwd=ROOT))
source=json.loads((ROOT/'simulator/schematic-source.json').read_text())
def normalize(s):
 s=re.sub(r'B[0-9OISG]+[T1]',lambda m:'B'+m[0][1:-1].translate(str.maketrans('OISG','0156'))+'T',s)
 s=s.replace('ALT','A1T').replace('XIT','X1T').replace('YIT','Y1T')
 tokens=re.findall(r'B\d{3,4}T|[A-Z]\d?T|\d{1,2}[AB]?T',s)
 return ' · '.join(tokens)
symbols={}
for page in [2,3,4]:
 im=Image.open(ROOT/f'simulator/assets/line-map/page-{page}.jpg').convert('RGB');a=np.array(im);scale=im.width/2048
 labs,n=label(a.max(2)<45);out=[]
 for sl in find_objects(labs):
  ys,xs=sl;w,h=xs.stop-xs.start,ys.stop-ys.start
  if 13<=w<=45 and 9<=h<=23 and w/h>1.1:
   out.append([round((xs.start+w/2)/scale,3),round((ys.start+h/2)/scale,3),round(w/scale,3),round(h/scale,3)])
 symbols[page]=out
out={}
for st in info:
 x,y,w,h=st['ref'];iw,ih=st['size'];sections=[]
 bx,by,bw,bh=st['bounds']
 for index,(a,b,c,name) in enumerate(st['cells']):
  px=x+(a+c/2)*w/iw;py=y+b*h/ih
  if not (bx<=px<=bx+bw and by<=py<=by+bh):continue
  nearby=[r for r in source['pages'][str(st['page'])]['sections'] if abs(r['x']+r['width']/2-px)<4 and abs(r['y']+r['height']/2-py)<3]
  secondary=nearby[0]['label'] if nearby else ''
  reviewed={('guro','T1T'):'YT1T',('guro','OT'):'DT',('geumcheon','54TIT'):'54T1T',('uiwang','OT'):'DT'}
  normalized=reviewed.get((st['id'],name),normalize(name))
  if not normalized and secondary:normalized=secondary
  sections.append([a,b,c,normalized])
 # Fill horizontal cells missed by the first extractor (for example continuous 6T/7T bars).
 min_local_y=min(c[1] for c in sections) if sections else 0
 for r in source['pages'][str(st['page'])]['sections']:
  cx=r['x']+r['width']/2;cy=r['y']+r['height']/2
  if not (bx<=cx<=bx+bw and by<=cy<=by+bh):continue
  left=(r['x']-x)*iw/w;right=left+r['width']*iw/w;row=(cy-y)*ih/h
  if row<min_local_y-20:continue
  remaining=[(left,right)]
  for a,b,c,_ in sections:
   if abs(b-row)>6:continue
   next_remaining=[]
   for start,end in remaining:
    if a>=end or a+c<=start:next_remaining.append((start,end));continue
    if a>start:next_remaining.append((start,a))
    if a+c<end:next_remaining.append((a+c,end))
   remaining=next_remaining
  for start,end in remaining:
   if end-start<18:continue
   label=normalize(r['label']) if start<=(left+right)/2<=end else ''
   sections.append([round(start,1),round(row,1),round(end-start,1),label])
 # These six isolated-cell candidates were checked against enlarged source regions.
 reviewed_fallback={('yeongdeungpo','TT'):'6T',('yeongdeungpo','ST'):'4T',('guro','OT'):'55T',('geumjeong','TT'):'',('geumjeong','IT'):'4T',('uiwang','OT'):'6T'}
 for c in sections:c[3]=reviewed_fallback.get((st['id'],c[3]),c[3])
 def local(p):return [round((p[0]-x)*iw/w,1),round((p[1]-y)*ih/h,1),*p[2:]]
 bx,by,bw,bh=st['bounds']
 caps=[local(p) for p in symbols[st['page']] if bx<=p[0]<=bx+bw and by<=p[1]<=by+bh]
 markers={2:[[20,350,'SP']],3:[[1310,104,'SP'],[443,435,'SS']],4:[[315,295,'SP'],[1190,270,'SS']]}
 markers=[local(p) for p in markers[st['page']] if bx<=p[0]<=bx+bw and by<=p[1]<=by+bh]
 out[st['id']]={'cells':sections,'capsules':caps,'markers':markers}
js="(function(root){'use strict';\n// Generated by tools/build-schematic-details.py; source identifiers retained as text.\nconst data="+json.dumps(out,ensure_ascii=False,separators=(',',':'))+";\nif(typeof module!=='undefined')module.exports=data;else root.SimSchematicDetails=data;\n})(typeof window!=='undefined'?window:globalThis);\n"
(ROOT/'simulator/schematic-details.js').write_text(js)
print('Built',sum(len(v['cells']) for v in out.values()),'sections and',sum(len(v['capsules']) for v in out.values()),'capsule symbols')
