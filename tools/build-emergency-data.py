#!/usr/bin/env python3
"""references/extracted/emergency/*.txt (비상시 조치 평가 대본, hwp 추출문) -> simulator/engine/emergency-data.js

원문 문장은 고치지 않고 번호별 단계(제목 + 통화·지시 줄)로 나눈다. 시뮬레이터 쪽 조작·열차 배치는 simulator/emergency.js에서 따로 정의한다.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'references' / 'extracted' / 'emergency'
OUT = ROOT / 'simulator' / 'emergency-data.js'
SKIP = re.compile(r'^(번\s*호|제\s*목|통\s*화|번호|\d{2}(-\d)?)$')       # table header cells and page markers (01-2 ...)
TITLE_NO = re.compile(r'\(관\)|\(기\)|[※★→⇒~=]|^[-<]|이상|[.!?]$|\(.*역\)')       # a line that already belongs to the step body


def clean(line):
    return re.sub(r'\s+$', '', line.replace(' ', ' '))


def parse(path):
    lines = [clean(l) for l in path.read_text(encoding='utf-8').split('\n')]
    lines = [l for l in lines if l.strip()]
    title = next(l.strip() for l in lines if re.match(r'\s*\d+(-\d)?\.\s', l))
    # header: everything before the first step number "1" that follows the table header cells
    start = next(i for i, l in enumerate(lines) if re.fullmatch(r'\s*1\s*', l))
    header = [l.strip() for l in lines[1:start] if not SKIP.match(l.strip())]
    steps, cur, expect = [], None, 1
    for l in lines[start:]:
        s = l.strip()
        if re.fullmatch(r'\d{1,2}', s) and int(s) == expect:
            cur = {'no': expect, 'title': [], 'body': []}
            steps.append(cur)
            expect += 1
            continue
        if SKIP.match(s) or cur is None:
            continue
        if not cur['body'] and len(s) <= 24 and not TITLE_NO.search(s):
            cur['title'].append(s)
        else:
            cur['body'].append(l.rstrip())
    return {'title': title, 'header': header, 'steps': [{'no': c['no'], 'title': ' · '.join(c['title']), 'body': c['body']} for c in steps]}


def main():
    names = sorted(p for p in SRC.glob('*.txt') if not p.name.startswith('비상시조치'))
    data = {}
    for p in names:
        key = re.match(r'(\d+(?:-\d)?)\.', p.name).group(1)
        d = parse(p)
        d['source'] = p.name.replace('.txt', '.hwp')
        data[key] = d
    variants = SRC / '비상시조치(상황변경시대응).txt'
    ref = [clean(l) for l in variants.read_text(encoding='utf-8').split('\n') if l.strip()]
    text = '// generated by tools/build-emergency-data.py from references/extracted/emergency (비상시 조치 대본 원문)\n'
    text += '(function(root){\nconst data=' + json.dumps({'scenarios': data, 'variants': {'source': variants.name.replace('.txt', '.hwp'), 'lines': ref}}, ensure_ascii=False, indent=1) + ';\n'
    text += "if(typeof module!=='undefined')module.exports=data;else root.SimEmergencyData=data;\n})(typeof window!=='undefined'?window:globalThis);\n"
    OUT.write_text(text, encoding='utf-8')
    for k, d in data.items():
        print(k, len(d['steps']), 'steps', sum(len(s['body']) for s in d['steps']), 'lines')


if __name__ == '__main__':
    sys.exit(main())
