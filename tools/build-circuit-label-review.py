"""Compile reviewed display corrections without changing engine data."""
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parents[1]
proof=json.loads((ROOT/'references/transcriptions/circuit-label-review.json').read_text())
corrections={sid:p['corrections'] for sid,p in proof['stations'].items() if p['corrections']}
additional={sid:p['additionalLabels'] for sid,p in proof['stations'].items() if p.get('additionalLabels')}
head='''/* Generated by tools/build-circuit-label-review.py.
 * Source slides, complete inventories and image hashes:
 * references/transcriptions/circuit-label-review.json.
 * Visible text only; engine resources, routes and train slots remain unchanged.
 */
(function(root){'use strict';
'''
body='const corrections='+json.dumps(corrections,ensure_ascii=False,indent=1)+';\nconst additionalLabels='+json.dumps(additional,ensure_ascii=False,indent=1)+';\n'
foot='''function labelFor(station,source){
 const fix=(corrections[station]||[]).find(c=>c.slice(0,3).every((v,i)=>Math.abs(v-source[i])<.1)&&c[3]===source[3]);
 return fix?fix[4]:source[3];
}
const api={corrections,additionalLabels,labelFor};if(typeof module!=='undefined')module.exports=api;else root.SimCircuitLabelReview=api;
})(typeof window!=='undefined'?window:globalThis);
'''
(ROOT/'simulator/ui/circuit-label-review.js').write_text(head+body+foot)
